package dk.tbsalling.aismessages.ais.messages.types;

/**
 * Meaning of the time stamp field of Messages 1, 2, 3, 9, 18, 19, 21 and 28 (ITU-R M.1371-6 Tables 46, 57, 68, 69,
 * 71 and 84, field "Time stamp"): whether it carries the UTC second of the report or the state of the electronic
 * position fixing system. Only {@link #Available} comes with a second.
 */
public enum TimeStampIndicator {
	/** 0-59: UTC second when the report was generated by the electronic position fixing system. */
	Available,
	/** 60 = time stamp not available (default). */
	NotAvailable,
	/** 61 = positioning system is in manual input mode. */
	ManualInputMode,
	/** 62 = electronic position fixing system operates in estimated (dead reckoning) mode. */
	DeadReckoningMode,
	/** 63 = positioning system is inoperative. */
	PositioningSystemInoperative
}
