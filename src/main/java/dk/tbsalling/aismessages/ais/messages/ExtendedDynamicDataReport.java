package dk.tbsalling.aismessages.ais.messages;

/**
 * Dynamic data report that additionally carries true heading and a time stamp: Messages 1, 2, 3
 * ({@link PositionReport}), 18 ({@link StandardClassBCSPositionReport}) and 19
 * ({@link ExtendedClassBEquipmentPositionReport}). Messages 9 and 27 only implement {@link DynamicDataReport}.
 */
public interface ExtendedDynamicDataReport extends DynamicDataReport {
    /** @return true heading in degrees, 0-359; 511 = not available (ITU-R M.1371-6 Tables 46, 68, 69) */
    int getTrueHeading();

    /** @return UTC second when the report was generated by the EPFS, 0-59; 60 = not available, 61 = manual input, 62 = dead reckoning, 63 = EPFS inoperative */
    int getSecond();
}
